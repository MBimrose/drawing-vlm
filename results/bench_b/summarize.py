"""Bench B + baselines tables (2026-10-10) -> results/bench_b/tables.md.
Paired tables = results/cycle2/eval_table.py (2,000-sample bootstrap, rng 0); plus per-family (Fusion F / ABC A) means.
    python results/bench_b/summarize.py"""
import json, os, subprocess, sys
import numpy as np
DV = "/projects/illinois/eng/ece/wpk/bimrose2/drawing_vlm"; E = f"{DV}/results/bench_b/eval"; PY = sys.executable
TAB = f"{DV}/results/cycle2/eval_table.py"
M = ("vote", "d0", "fe", "mean", "bo", "ex")


def run(prefix, models, refs):
    have = [m for m in models if os.path.exists(f"{E}/{prefix}_{m}.json")]
    if not have: return "(no results yet)\n"
    r = subprocess.run([PY, TAB, *have, "--dir", E, "--prefix", prefix, "--refs", refs], capture_output=True, text=True)
    return r.stdout + r.stderr


def fam(prefix, models):
    out = ["| model | family | n | " + " | ".join(M) + " |", "|---|---|---|" + "---|" * len(M)]
    for n in models:
        p = f"{E}/{prefix}_{n}.json"
        if not os.path.exists(p): continue
        rows = {}
        for q in json.load(open(p))["candidates"]:
            c = sorted(q["cands"], key=lambda c: c.get("draw", 0)); iou = [float(x.get("iou") or 0) for x in c]; ex = [bool(x.get("exec")) for x in c]
            rows[q["key"]] = dict(d0=iou[0], mean=np.mean(iou), fe=next((v for v, e in zip(iou, ex) if e), 0.0), bo=max(iou), ex=np.mean(ex))
        cf = f"{E}/{prefix}_{n}_consistency.json"
        if os.path.exists(cf):
            for k, v in json.load(open(cf))["per_part"].items():
                if k in rows: rows[k]["vote"] = float(v["consistency"])
        for f in "FA":
            ks = [k for k in rows if k[0] == f]
            cells = [f"{np.mean([rows[k][m] for k in ks]):.3f}" if all(m in rows[k] for k in ks) else "n/a" for m in M]
            out.append(f"| {n} | {f} | {len(ks)} | " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


main4 = ["e55ctl", "rft1_rl2_s120", "ent_t10_s120", "rft2_rl_s60"]
base = ["dsv41", "dsv41_1call", "qwenbase"]
txt = ["# Bench B + baselines tables (generated by summarize.py)\n",
       "vote = consistency medoid; d0 = draw 0 (greedy for the Qwen-family models, sampled for DeepSeek); fe = first executing draw;",
       "mean = mean candidate IoU; bo = best-of-8 (oracle); ex = execution rate. Paired 95% bootstrap CIs.\n",
       "## Bench B (280 parts, frozen) -- the four generators, paired vs e55ctl\n", run("benchb", main4, "e55ctl"),
       "\n## Bench B -- rft2_rl_s60 vs the others\n", run("benchb", ["rft2_rl_s60"], "e55ctl,rft1_rl2_s120,ent_t10_s120"),
       "\n## Bench B -- baselines vs e55ctl and rft2_rl_s60\n", run("benchb", base, "e55ctl,rft2_rl_s60"),
       "\n## 144-part real bench -- baselines vs e55ctl and rft2_rl_s60 (references = results/grpo_eval files)\n",
       run("real", base, "e55ctl,rft2_rl_s60"),
       "\n## 144-part real bench -- rft2_rl_s60 vs the others (reference, unchanged)\n", run("real", ["rft2_rl_s60"], "e55ctl,rft1_rl2_s120,ent_t10_s120"),
       "\n## Per family, bench B\n", fam("benchb", main4 + base), "\n## Per family, 144 bench\n", fam("real", main4 + base)]
open(f"{DV}/results/bench_b/tables.md", "w").write("\n".join(txt)); print("\n".join(txt))
